export const getAnomaliesForTransformer = (transformer) => {
  const items = [];
  if (transformer.temperature >= 82) {
    items.push({
      title: 'Overheating Detected',
      severity: transformer.temperature >= 92 ? 'CRITICAL' : 'WARNING',
      description: 'Thermal model reports abnormal winding and oil temperature rise.',
      detectedTime: '6 min ago',
      recommendedAction: 'Reduce load and inspect cooling system operation.',
    });
  }
  if (transformer.moistureLevel >= 16) {
    items.push({
      title: 'High Moisture Content',
      severity: 'WARNING',
      description: 'Moisture sensors indicate elevated ppm in transformer oil.',
      detectedTime: '18 min ago',
      recommendedAction: 'Inspect silica gel breather and plan oil dehydration.',
    });
  }
  if (transformer.partialDischarge >= 18) {
    items.push({
      title: 'Insulation Degradation',
      severity: transformer.partialDischarge >= 38 ? 'CRITICAL' : 'WARNING',
      description: 'Partial discharge activity suggests insulation stress.',
      detectedTime: '24 min ago',
      recommendedAction: 'Perform DGA sampling and insulation diagnostics.',
    });
  }
  if (transformer.loadPercentage >= 80) {
    items.push({
      title: 'Overload Condition',
      severity: transformer.loadPercentage >= 92 ? 'CRITICAL' : 'WARNING',
      description: 'Load factor has remained above operational planning limit.',
      detectedTime: '10 min ago',
      recommendedAction: 'Shift load through feeder automation where available.',
    });
  }
  if (transformer.vibrationLevel >= 0.25) {
    items.push({
      title: 'Vibration Anomaly',
      severity: 'ADVISORY',
      description: 'Mechanical vibration signature differs from baseline profile.',
      detectedTime: '31 min ago',
      recommendedAction: 'Inspect fans, pumps, and mounting hardware.',
    });
  }
  return items.length
    ? items
    : [{
        title: 'No Active Anomaly',
        severity: 'NORMAL',
        description: 'Operational telemetry is inside learned baseline limits.',
        detectedTime: 'Live',
        recommendedAction: 'Continue routine monitoring.',
      }];
};
